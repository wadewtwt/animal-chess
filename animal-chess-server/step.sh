#!/bin/bash

# 获取当前脚本所在目录的绝对路径，确保在正确的路径下执行
BASE_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
cd "$BASE_DIR"

echo "=================================================="
echo " 正在重新部署并启动斗兽棋后端服务..."
echo "=================================================="

# 1. 尝试拉取最新代码
if [ -d .git ] || git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    echo "检测到 Git 仓库，正在拉取最新代码..."
    git pull
else
    echo "未检测到 Git 仓库，跳过拉取代码步骤。"
fi

# 2. 停止并删除老容器及本地旧镜像（防止老版本缓存残留）
echo "正在停止并彻底清除旧的容器及关联的本地镜像..."
docker compose down --rmi local

# 3. 清理虚悬镜像（符合运维规范，避免多次构建导致磁盘爆满）
docker image prune -f

# 4. 重新编译镜像并在后台启动新容器
echo "正在构建最新镜像并启动新容器..."
docker compose up -d --build

echo "=================================================="
echo " 服务已拉起，当前容器运行状态："
echo "=================================================="
docker compose ps

echo "=================================================="
echo " 显示实时日志 (按 Ctrl+C 退出日志追踪) :"
echo "=================================================="
docker compose logs -f --tail=50
